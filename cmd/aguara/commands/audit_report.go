package commands

import (
	"fmt"
	"io"
	"strings"

	"github.com/garagon/aguara/internal/output"
)

// renderAuditMarkdown renders the audit as GitHub-flavored Markdown for job
// summaries and PR comments: the verdict and triage decision, the package
// findings, the content findings (the same tables as scan's Markdown
// report) and the recommended next steps.
func renderAuditMarkdown(w io.Writer, result *AuditResult) {
	plain := output.NewStyle(true)
	v := result.Verdict

	fmt.Fprintf(w, "## Aguara Audit\n\n")
	fmt.Fprintf(w, "> **Verdict: %s** · **Triage: %s** · `%s`\n\n",
		output.EscapeMarkdown(strings.ToUpper(v.Status)),
		output.EscapeMarkdown(strings.ToUpper(result.Triage.Decision)),
		output.EscapeMarkdown(result.Target))
	if result.Triage.Summary != "" {
		fmt.Fprintf(w, "%s\n\n", output.EscapeMarkdown(result.Triage.Summary))
	}
	fmt.Fprintf(w, "Package check: %d critical, %d warning, %d info · Content scan: %d critical, %d high, %d medium, %d low, %d info\n\n",
		v.CheckCriticals, v.CheckWarnings, v.CheckInfos,
		v.ScanCriticals, v.ScanHighs, v.ScanMediums, v.ScanLows, v.ScanInfos)

	fmt.Fprintf(w, "### Package check\n\n")
	if line := packageCoverageLine(result.Check.Coverage); line != "" {
		fmt.Fprintf(w, "%s\n\n", output.EscapeMarkdown(line))
	}
	notes := unsupportedEvidenceLines(result.Check.Coverage, result.Target)
	if note := unpinnedNote(result.Check); note != "" {
		notes = append(notes, note)
	}
	for _, note := range notes {
		fmt.Fprintf(w, "- %s\n", output.EscapeMarkdown(note))
	}
	if len(notes) > 0 {
		fmt.Fprintln(w)
	}
	if len(result.Check.Findings) == 0 {
		fmt.Fprintf(w, "%s\n\n", output.EscapeMarkdown(noPackageFindingsLine(plain, result.Check.Coverage)))
	} else {
		writePackageFindingsMarkdown(w, result.Check.Findings, result.Target)
	}

	fmt.Fprintf(w, "### Content scan\n\n")
	fmt.Fprintf(w, "%d files scanned · %s\n\n", result.Scan.FilesScanned,
		output.RulesLabel(detections(result.rules), result.Scan.RulesLoaded))
	switch {
	case len(result.Scan.Findings) == 0 && result.Scan.FilesScanned == 0:
		fmt.Fprintf(w, "%s\n\n", output.EscapeMarkdown(output.NothingScannedMessage(result.Scan)))
	case len(result.Scan.Findings) == 0:
		fmt.Fprintf(w, "No content findings.\n\n")
	default:
		(&output.MarkdownFormatter{}).WriteFindings(w, result.Scan.Findings)
	}
	if line := output.SuppressionLine(result.Scan.Suppressed); line != "" {
		fmt.Fprintf(w, "<sub>%s</sub>\n\n", output.EscapeMarkdown(line))
	}

	if len(result.Triage.Reasons) > 0 || len(result.Triage.RecommendedNextSteps) > 0 {
		fmt.Fprintf(w, "### Triage\n\n")
		for _, r := range result.Triage.Reasons {
			fmt.Fprintf(w, "- **%s** (%s): %s\n", output.EscapeMarkdown(r.Kind), output.EscapeMarkdown(r.Severity), output.EscapeMarkdown(r.Message))
		}
		if len(result.Triage.Reasons) > 0 {
			fmt.Fprintln(w)
		}
		for i, step := range result.Triage.RecommendedNextSteps {
			fmt.Fprintf(w, "%d. %s\n", i+1, output.EscapeMarkdown(step))
		}
		if len(result.Triage.RecommendedNextSteps) > 0 {
			fmt.Fprintln(w)
		}
	}
	fmt.Fprintf(w, "Agent handoff: **%s** · install dependencies: %s · run project code: %s\n\n",
		output.EscapeMarkdown(result.Handoff.Status), yesNo(result.Plan.CanInstallDependencies), yesNo(result.Plan.CanExecuteProjectCode))
	fmt.Fprintf(w, "<sub>Generated by [Aguara](https://github.com/garagon/aguara) %s</sub>\n", output.EscapeMarkdown(Version))
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}
